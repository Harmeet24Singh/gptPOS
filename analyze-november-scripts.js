const { MongoClient } = require("mongodb");
require("dotenv").config();

// MongoDB connection from environment
const uri = process.env.MONGO_URI || "mongodb://localhost:27017";
const dbName = process.env.MONGO_DB || "convenience_store";

async function analyzeNovemberScriptData() {
  const client = new MongoClient(uri);

  try {
    await client.connect();
    console.log("Connected to MongoDB");

    const db = client.db(dbName);
    const collection = db.collection("transactions");

    console.log("=== NOVEMBER SCRIPT-GENERATED DATA ANALYSIS ===");

    // Look for transactions that might have been generated by the November scripts
    // Nov 18 and Nov 26 specifically

    const nov18Start = new Date("2025-11-18T00:00:00.000Z");
    const nov18End = new Date("2025-11-19T00:00:00.000Z");
    const nov26Start = new Date("2025-11-26T00:00:00.000Z");
    const nov26End = new Date("2025-11-27T00:00:00.000Z");

    console.log("=== NOVEMBER 18 DATA ===");
    const nov18Transactions = await collection
      .find({
        timestamp: { $gte: nov18Start, $lt: nov18End },
      })
      .toArray();

    console.log(`November 18 transactions: ${nov18Transactions.length}`);

    let nov18Total = 0;
    const nov18Categories = {};
    let nov18GroceryTotal = 0;
    let nov18GroceryCount = 0;

    nov18Transactions.forEach((t) => {
      nov18Total += t.total;

      if (t.items) {
        t.items.forEach((item) => {
          const category = item.category || "Unknown";
          nov18Categories[category] = nov18Categories[category] || {
            count: 0,
            total: 0,
          };
          nov18Categories[category].count++;
          nov18Categories[category].total += t.total;

          // Check for grocery-like categories
          if (
            [
              "Grocery",
              "Food",
              "Beverages",
              "Snacks",
              "Bakery",
              "Candy",
              "Dairy",
              "Fresh Produce",
            ].includes(category)
          ) {
            nov18GroceryCount++;
            nov18GroceryTotal += t.total;
          }
        });
      }
    });

    console.log(`November 18 total sales: $${nov18Total.toFixed(2)}`);
    console.log(
      `November 18 grocery-like sales: $${nov18GroceryTotal.toFixed(
        2
      )} (${nov18GroceryCount} items)`
    );

    console.log("November 18 categories:");
    Object.entries(nov18Categories)
      .sort((a, b) => b[1].total - a[1].total)
      .forEach(([cat, data]) => {
        console.log(`  ${cat}: ${data.count} items, $${data.total.toFixed(2)}`);
      });

    console.log("\n=== NOVEMBER 26 DATA ===");
    const nov26Transactions = await collection
      .find({
        timestamp: { $gte: nov26Start, $lt: nov26End },
      })
      .toArray();

    console.log(`November 26 transactions: ${nov26Transactions.length}`);

    let nov26Total = 0;
    const nov26Categories = {};
    let nov26GroceryTotal = 0;
    let nov26GroceryCount = 0;

    nov26Transactions.forEach((t) => {
      nov26Total += t.total;

      if (t.items) {
        t.items.forEach((item) => {
          const category = item.category || "Unknown";
          nov26Categories[category] = nov26Categories[category] || {
            count: 0,
            total: 0,
          };
          nov26Categories[category].count++;
          nov26Categories[category].total += t.total;

          // Check for grocery-like categories
          if (
            [
              "Grocery",
              "Food",
              "Beverages",
              "Snacks",
              "Bakery",
              "Candy",
              "Dairy",
              "Fresh Produce",
            ].includes(category)
          ) {
            nov26GroceryCount++;
            nov26GroceryTotal += t.total;
          }
        });
      }
    });

    console.log(`November 26 total sales: $${nov26Total.toFixed(2)}`);
    console.log(
      `November 26 grocery-like sales: $${nov26GroceryTotal.toFixed(
        2
      )} (${nov26GroceryCount} items)`
    );

    console.log("November 26 categories:");
    Object.entries(nov26Categories)
      .sort((a, b) => b[1].total - a[1].total)
      .forEach(([cat, data]) => {
        console.log(`  ${cat}: ${data.count} items, $${data.total.toFixed(2)}`);
      });

    // Check if the combined grocery-like totals from these dates approach $8025.96
    const combinedGroceryLike = nov18GroceryTotal + nov26GroceryTotal;
    console.log(`\n=== ANALYSIS ===`);
    console.log(
      `Combined Nov 18 + Nov 26 grocery-like: $${combinedGroceryLike.toFixed(
        2
      )}`
    );

    // Also check if there are transactions that might be categorized differently
    // Look at all November transactions with Unknown category
    const allNovemberUnknown = await collection
      .find({
        timestamp: {
          $gte: new Date("2025-11-01T00:00:00.000Z"),
          $lt: new Date("2025-12-01T00:00:00.000Z"),
        },
        "items.category": null,
      })
      .toArray();

    let unknownTotal = 0;
    allNovemberUnknown.forEach((t) => (unknownTotal += t.total));

    console.log(
      `November transactions with unknown/null category: ${allNovemberUnknown.length}`
    );
    console.log(`Unknown category total: $${unknownTotal.toFixed(2)}`);

    // Show a few examples of unknown category transactions
    if (allNovemberUnknown.length > 0) {
      console.log("\nFirst 5 unknown category transactions:");
      allNovemberUnknown.slice(0, 5).forEach((t, i) => {
        const itemNames = t.items
          ? t.items.map((item) => item.name || "unnamed").join(", ")
          : "no items";
        console.log(
          `${i + 1}. ${t.timestamp.toISOString()} | $${
            t.total
          } | Items: ${itemNames}`
        );
      });
    }

    // Final check: see if some combination of categories equals ~$8025.96
    console.log("\n=== CHECKING FOR $8025.96 SOURCE ===");

    // Get all November categories and their totals
    const allNovemberTransactions = await collection
      .find({
        timestamp: {
          $gte: new Date("2025-11-01T00:00:00.000Z"),
          $lt: new Date("2025-12-01T00:00:00.000Z"),
        },
      })
      .toArray();

    const allCategories = {};
    allNovemberTransactions.forEach((t) => {
      if (t.items && t.items.length > 0) {
        t.items.forEach((item) => {
          const category = item.category || "Unknown";
          allCategories[category] = (allCategories[category] || 0) + t.total;
        });
      } else {
        allCategories["No Items"] = (allCategories["No Items"] || 0) + t.total;
      }
    });

    // Look for combinations that might equal ~$8025.96
    const targetAmount = 8025.96;
    const categoryNames = Object.keys(allCategories);

    console.log("Looking for combinations close to $8025.96:");

    // Check single categories
    Object.entries(allCategories).forEach(([cat, total]) => {
      if (Math.abs(total - targetAmount) < 500) {
        console.log(
          `Single category ${cat}: $${total.toFixed(2)} (diff: ${Math.abs(
            total - targetAmount
          ).toFixed(2)})`
        );
      }
    });

    // Check if Unknown + some grocery categories = ~$8025.96
    const unknownAmount = allCategories["Unknown"] || 0;
    const foodAmount = allCategories["Food"] || 0;
    const groceryAmount = allCategories["Grocery"] || 0;
    const beveragesAmount = allCategories["Beverages"] || 0;
    const snacksAmount = allCategories["Snacks"] || 0;

    const possibleCombination =
      foodAmount + groceryAmount + beveragesAmount + snacksAmount;
    console.log(
      `Food + Grocery + Beverages + Snacks: $${possibleCombination.toFixed(2)}`
    );

    if (Math.abs(possibleCombination - targetAmount) < 1000) {
      console.log(`*** This combination is close to the target! ***`);
    }
  } catch (error) {
    console.error("Error analyzing November script data:", error);
  } finally {
    await client.close();
    console.log("\nConnection closed");
  }
}

// Run the analysis
analyzeNovemberScriptData();
